import numpy as np
import pandas as pd
from sklearn.linear_model import LinearRegression
from sklearn.ensemble import RandomForestRegressor
from sklearn.model_selection import train_test_split
from sklearn.metrics import mean_squared_error
import matplotlib.pyplot as plt

np.random.seed(42)

time_steps = 100
t = np.arange(time_steps)

x = 2 * t + np.random.normal(0, 5, time_steps)
y = 3 * t + np.random.normal(0, 5, time_steps)

data = pd.DataFrame({
    "time": t,
    "x": x,
    "y": y
})

data["vx"] = data["x"].diff().fillna(0)
data["vy"] = data["y"].diff().fillna(0)

data["x_next"] = data["x"].shift(-1)
data["y_next"] = data["y"].shift(-1)

data = data.dropna()

features = ["x", "y", "vx", "vy"]
X = data[features]
y_target = data[["x_next", "y_next"]]

X_train, X_test, y_train, y_test = train_test_split(
    X, y_target, test_size=0.2, random_state=42
)

lr_model = LinearRegression()
lr_model.fit(X_train, y_train)
lr_pred = lr_model.predict(X_test)

rf_model = RandomForestRegressor(n_estimators=100, random_state=42)
rf_model.fit(X_train, y_train)
rf_pred = rf_model.predict(X_test)

lr_mse = mean_squared_error(y_test, lr_pred)
rf_mse = mean_squared_error(y_test, rf_pred)

print("Linear Regression MSE:", lr_mse)
print("Random Forest MSE:", rf_mse)

plt.scatter(y_test["x_next"], y_test["y_next"])
plt.scatter(rf_pred[:, 0], rf_pred[:, 1])
plt.xlabel("X")
plt.ylabel("Y")
plt.title("Motion Prediction")
plt.show()